#!/usr/bin/env python3
"""Embed the vendored bcdec scalar decoders as Metal source for no-BC GPUs.

The algorithms stay upstream's: only address spaces, 64-bit spelling and local
constant declarations change. The unused C-union float conversion is omitted;
BC6H uses its half-float decoder. Run with --check to verify the checked-in file.
"""
import argparse
import json
import re
from pathlib import Path


def source():
    text = (Path(__file__).resolve().parents[2] / 'third_party/bcdec/bcdec.h').read_text()
    text = text.split('#ifdef BCDEC_IMPLEMENTATION', 1)[1]
    text = text[:text.rindex('#endif')]
    for name in ('bcdec__half_to_float_quick', 'bcdec_bc6h_float'):
        match = re.search(r'^(?:static|BCDECDEF) [^\n]*\b' + name + r'\([^\n]*\)\s*\{', text, re.M)
        assert match is not None
        end, depth = match.end(), 1
        while depth:
            depth += (text[end] == '{') - (text[end] == '}')
            end += 1
        text = text[:match.start()] + text[end:]
    text = text.replace('static const ', 'const ').replace('unsigned long long', 'ulong')
    text = re.sub(r'(?m)^(\s+)static ', r'\1const ', text)
    text = re.sub(r'\b(?:const\s+)?(?:void|unsigned char|signed char|unsigned short|unsigned int|float|int|char|bcdec__bitstream_t)\s*\*',
                  lambda m: 'thread ' + m[0], text)
    text = text.replace('thread int* weights', 'thread const int* weights')
    return '#include <metal_stdlib>\nusing namespace metal;\n#define BCDECDEF static\n#define BCDEC_BC4BC5_PRECISE\n' + text


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = Path(__file__).with_name('nvn_bcdec_msl.h')
    content = '// Generated by bcdec_msl.py from dm/third_party/bcdec/bcdec.h (MIT). Do not edit.\n'
    content += 'static const char k_bcdec_msl[] =\n' + ''.join(json.dumps(line) + '\n' for line in source().splitlines(keepends=True)) + ';\n'
    if args.check:
        if not output.is_file() or output.read_text() != content:
            parser.exit(1, 'BC decoder Metal source is stale: run dm/gfx/tex/bcdec_msl.py\n')
    else:
        output.write_text(content)


if __name__ == '__main__':
    main()
